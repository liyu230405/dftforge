def _write_text(tmp_path: Path, name: str, content: str) -> Path:
    p = tmp_path / name
    p.write_text(content)
    return p


# ── Format detection ──────────────────────────────────────────────────────────

class TestFormatDetection:
    def test_detect_poscar(self):
        assert _detect_format_from_text("POSCAR\nSi\n1.0\n...") == "poscar"

    def test_detect_atom_block(self):
        assert _detect_format_from_text("ATOM\nSi 0 0 0\n") == "poscar"

    def test_detect_direct_keyword(self):
        assert _detect_format_from_text("Direct\nSi 0 0 0\n") == "poscar"

    def test_detect_qe_sections(self):
        text = "ATOMIC_SPECIES\nATOMIC_POSITIONS (crystal)\n"
        assert _detect_format_from_text(text) == "qe_input"

    def test_detect_xyz(self):
        text = "2\ncomment\nSi 0 0 0\nSi 1 1 1\n"
        assert _detect_format_from_text(text) == "xyz"

    def test_detect_unknown(self):
        assert _detect_format_from_text("hello world") == "unknown"


# ── CIF parser ───────────────────────────────────────────────────────────────

class TestParseCIF:
    def test_si_cif(self, tmp_path: Path):
        importer = StructureImporter()
        p = _write_text(tmp_path, "si.cif", _SI_CIF)
        report = importer.import_structure(p)
        assert report.success is True
        assert report.format == "cif"
        assert report.formula == "Si2"
        assert report.natoms == 2

    def test_cif_invalid_element_raises(self, tmp_path: Path):
        cif = """data_Bad
_cell_length_a 3.0
loop_
_atom_site_type_symbol
_atom_site_fract_x
_atom_site_fract_y
_atom_site_fract_z
Xx 0 0 0
"""
        importer = StructureImporter()
        p = _write_text(tmp_path, "bad.cif", cif)
        report = importer.import_structure(p)
        assert report.success is False
        assert any("Parsing failed" in e or "Unsupported element symbol" in e for e in report.errors)


