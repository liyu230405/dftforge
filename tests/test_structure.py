# ── Explicit structure parser ─────────────────────────────────────────────────

class TestExplicitStructure:
    def test_valid_explicit(self):
        source = {
            "lattice": [[4.0, 0, 0], [0, 4.0, 0], [0, 0, 4.0]],
            "positions": [[0, 0, 0], [2, 2, 2]],
            "symbols": ["Si", "Si"],
            "fractional": False,
        }
        atoms = _build_from_explicit(**source)
        assert len(atoms) == 2
        assert atoms.get_chemical_symbols() == ["Si", "Si"]

    def test_fractional_positions(self):
        source = {
            "lattice": [[4.0, 0, 0], [0, 4.0, 0], [0, 0, 4.0]],
            "positions": [[0.0, 0.0, 0.0], [0.5, 0.5, 0.5]],
            "symbols": ["Si", "Si"],
            "fractional": True,
        }
        atoms = _build_from_explicit(**source)
        assert len(atoms) == 2
        expected = np.array([[0.0, 0.0, 0.0], [2.0, 2.0, 2.0]])
        assert np.allclose(atoms.get_positions(), expected)


# ── Validation rules ──────────────────────────────────────────────────────────

class TestValidation:
    def test_valid_structure_success(self):
        importer = StructureImporter()
        report = importer.import_structure(_SI_QE, format="qe_input")
        assert report.success is True
        assert report.nspecies == 1
        assert report.space_group is not None

    def test_non_periodic_rejected(self):
        importer = StructureImporter()
        from ase import Atoms as AseAtoms
        atoms = AseAtoms("Si2", positions=[[0, 0, 0], [1, 1, 1]], pbc=False)
        report = ValidationReport(success=False)
        from dft_forge.structure import _validate_periodicity
        report.errors.extend(_validate_periodicity(atoms))
        assert report.errors
        assert any("not periodic" in e for e in report.errors)

    def test_unsupported_element_rejected(self, tmp_path: Path):
        cif = """data_Bad
_cell_length_a 3.0
loop_
_atom_site_type_symbol
_atom_site_fract_x
_atom_site_fract_y
_atom_site_fract_z
Xx 0 0 0
"""
        importer = StructureImporter()
        p = _write_text(tmp_path, "bad.cif", cif)
        report = importer.import_structure(p)
        assert report.success is False
        assert any("Parsing failed" in e or "Unsupported element symbol" in e for e in report.errors)

    def test_unknown_format_rejected(self):
        importer = StructureImporter()
        report = importer.import_structure("this is not a structure", format="unknown")
        assert report.success is False
        assert any("Unsupported or unknown structure format" in e for e in report.errors)

    def test_too_close_atoms_rejected(self):
        source = {
            "lattice": [[10, 0, 0], [0, 10, 0], [0, 0, 10]],
            "positions": [[0, 0, 0], [0.01, 0.01, 0.01]],
            "symbols": ["Si", "Si"],
            "fractional": False,
        }
        importer = StructureImporter(min_nearest_neighbor_angstrom=0.8)
        report = importer.import_structure(source, format="explicit")
        assert report.success is False
        assert any("Nearest-neighbor distance" in e for e in report.errors)


# ── Dynamic catalog helpers ───────────────────────────────────────────────────

class TestDynamicCatalog:
    def test_build_dynamic_profile_from_valid_report(self):
        importer = StructureImporter()
        report = importer.import_structure(_SI_QE, format="qe_input")
        assert report.success is True
        profile = build_dynamic_material_profile(
            report,
            pseudos={"Si": "Si_r.upf"},
            is_metal=False,
        )
        assert profile.formula == "Si2"
        assert profile.ibrav == 0
        assert profile.nspecies == 1
        assert profile.pseudos == {"Si": "Si_r.upf"}

    def test_build_dynamic_profile_from_failed_report_raises(self):
        report = ValidationReport(success=False, atoms=None)
        with pytest.raises(ValueError, match="failed validation report"):
            build_dynamic_material_profile(report)

    def test_register_dynamic_material(self):
        importer = StructureImporter()
        report = importer.import_structure(_SI_QE, format="qe_input")
        profile = build_dynamic_material_profile(
            report,
            pseudos={"Si": "Si_r.upf"},
            is_metal=False,
        )
        before = list_materials()
        register_dynamic_material("dyn_Si2", profile)
        after = list_materials()
        assert "dyn_Si2" in after
        assert after.index("dyn_Si2") > after.index("Si")
        # Cleanup to avoid polluting later tests if module state persists.
        from dft_forge.catalog import MATERIALS
        MATERIALS.pop("dyn_Si2", None)

    def test_build_dynamic_task_spec(self):
        importer = StructureImporter()
        report = importer.import_structure(_SI_QE, format="qe_input")
        profile = build_dynamic_material_profile(
            report,
            pseudos={"Si": "Si_r.upf"},
            is_metal=False,
        )
        spec = build_dynamic_task_spec(
            "T1_dyn_Si2_vcrelax",
            profile,
            task_type="T1",
            parameters={"ecutwfc": 20.0},
        )
        assert spec.task_id == "T1_dyn_Si2_vcrelax"
        assert spec.material_profile.formula == "Si2"
        assert spec.metadata.get("dynamic") is True
